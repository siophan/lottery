// 自测：用手算真值验证过滤引擎
const { filter, sum, span } = require('./pl3');
let pass = 0, fail = 0;
function eq(name, got, want) {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; console.log('  ok  ', name); }
  else { fail++; console.log('  FAIL', name, '\n    got =', g, '\n    want=', w); }
}

// 1) 和值=1 的直选：000?no(和0). 和值1 => 001,010,100
eq('和值=1', filter([{ id:'plsr3002', arr:[1] }]), ['001','010','100']);

// 2) 和值=27 => 只有 999
eq('和值=27', filter([{ id:'plsr3002', arr:[27] }]), ['999']);

// 3) 跨度=0 => 三位相同：000,111,...,999 共10注
eq('跨度=0 计数', filter([{ id:'plsr3004', arr:[0] }]).length, 10);

// 4) 和值=1 且 跨度=1 => 001,010,100 跨度均为1 => 全过
eq('和值1∩跨度1', filter([{ id:'plsr3002', arr:[1] }, { id:'plsr3004', arr:[1] }]), ['001','010','100']);

// 5) 反选：和值≠1 的数量 = 1000 - 3
eq('和值≠1 计数(反选)', filter([{ id:'plsr3002', arr:[1], reaction:1 }]).length, 997);

// 6) 胆码：选5,至少开出1个 => 含数字5的号码数。
//    不含5的号码=9^3=729，含5的=1000-729=271
eq('胆码5 开出≥1 计数', filter([{ id:'plsr3001', arr:[5], kai:1 }]).length, 271);

// 7) 胆码:选3和7,至少开出2个(两个胆都要出现)
//    含3且含7：容斥 = 1000 - |无3| - |无7| + |无3且无7| = 1000-729-729+512=54
eq('胆码3,7 开出≥2 计数', filter([{ id:'plsr3001', arr:[3,7], kai:2 }]).length, 54);

// --- 第二批：数学无歧义条件 ---

// 8) 定位：百位∈{1,2}，其余不限 => 2*10*10 = 200
eq('定位 百∈{1,2} 计数', filter([{ id:'plsr3025', pos:[[1,2],[],[]] }]).length, 200);

// 9) 定位：百{1} 十{2} 个{3} => 唯一 123
eq('定位 精确 123', filter([{ id:'plsr3025', pos:[[1],[2],[3]] }]), ['123']);

// 10) 最大数=9 => 含9的号码 = 1000-9^3 = 271
eq('最大数=9 计数', filter([{ id:'plsr3023', max:[9] }]).length, 271);

// 11) 组选形态-豹子 => 10 注
eq('豹子 计数', filter([{ id:'plsr3015', arr:['豹子'] }]).length, 10);

// 12) 组选形态-组六(全不同) => 10*9*8 = 720
eq('组六 计数', filter([{ id:'plsr3015', arr:['组六'] }]).length, 720);

// 13) 组选形态-组三(恰两位相同) => 1000-10-720 = 270
eq('组三 计数', filter([{ id:'plsr3015', arr:['组三'] }]).length, 270);

// 14) 顺子：012,123,...,789 共8组连续三元组，各6种排列 => 8*6 = 48
//     注意"012 是否算顺子"是 app 约定，待参照确认；本实现含 012。
eq('顺子 计数(含012)', filter([{ id:'plsr3015', arr:['顺子'] }]).length, 48);

// 15) 各位差值三组都=0 => 三位相同(豹子) => 10
eq('各位差值全0 => 豹子', filter([{ id:'plsr3009', d1:[0], d2:[0], d3:[0] }]).length, 10);

// 16) 仅约束 |百-十|=0（其余不限）=> 百=十，个任意 => 10*10 = 100
eq('|百-十|=0 计数', filter([{ id:'plsr3009', d1:[0] }]).length, 100);

console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
process.exit(fail ? 1 : 0);
